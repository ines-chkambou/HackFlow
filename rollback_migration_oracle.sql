-- ============================================================
-- rollback_migration_oracle.sql
-- Projet : SmartHackathon / HackFlow Jury
-- Cible  : Oracle XE 11g, schema INES
--
-- ATTENTION : SCRIPT DESTRUCTIF.
-- Il supprime uniquement les objets crees par la migration :
--   JURY, PROJET, EVALUATION, PARAMETRES_JURY, SESSION_EVALUATION,
--   JURY_SEQ, EVAL_SEQ, SESSION_SEQ,
--   JURY_BIR, EVAL_BIR, SESSION_BIR.
--
-- Il ne supprime pas l'utilisateur INES.
-- Il ne touche pas aux autres schemas.
-- Il ne modifie pas SQLite.
-- Il ne doit etre execute qu'avec une autorisation explicite.
-- ============================================================

SET SERVEROUTPUT ON SIZE 1000000
SET ECHO OFF
SET FEEDBACK ON
SET VERIFY OFF
SET DEFINE ON
WHENEVER SQLERROR EXIT FAILURE
WHENEVER OSERROR EXIT FAILURE

ACCEPT confirmation CHAR PROMPT 'Tapez OUI pour confirmer le rollback : '

DECLARE
  v_confirmation VARCHAR2(10) := UPPER('&confirmation');
BEGIN
  IF v_confirmation IS NULL OR v_confirmation <> 'OUI' THEN
    RAISE_APPLICATION_ERROR(-20010,
      'Rollback annule : confirmation differente de OUI.');
  END IF;
END;
/

SET DEFINE OFF
WHENEVER SQLERROR CONTINUE

PROMPT Suppression des triggers...
BEGIN
  EXECUTE IMMEDIATE 'DROP TRIGGER JURY_BIR';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('JURY_BIR : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TRIGGER EVAL_BIR';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('EVAL_BIR : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TRIGGER SESSION_BIR';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('SESSION_BIR : ' || SQLERRM);
END;
/

PROMPT Suppression des tables dans l'ordre inverse...
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE SESSION_EVALUATION CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('SESSION_EVALUATION : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE EVALUATION CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('EVALUATION : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE PARAMETRES_JURY CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('PARAMETRES_JURY : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE PROJET CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('PROJET : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE JURY CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('JURY : ' || SQLERRM);
END;
/

PROMPT Suppression des sequences...
BEGIN
  EXECUTE IMMEDIATE 'DROP SEQUENCE JURY_SEQ';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('JURY_SEQ : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP SEQUENCE EVAL_SEQ';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('EVAL_SEQ : ' || SQLERRM);
END;
/
BEGIN
  EXECUTE IMMEDIATE 'DROP SEQUENCE SESSION_SEQ';
EXCEPTION WHEN OTHERS THEN
  DBMS_OUTPUT.PUT_LINE('SESSION_SEQ : ' || SQLERRM);
END;
/

PROMPT ============================================================
PROMPT Rollback termine. Verifier USER_TABLES, USER_SEQUENCES,
PROMPT USER_TRIGGERS et USER_INDEXES pour confirmer l'absence d'objets.
PROMPT ============================================================
